/**
 * Balance report: plays the real simulation with several bot playstyles and
 * prints when each era is reached. Run with `pnpm balance [hours]`.
 * Writes docs/balance.md so tuning changes are reviewable in diffs.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { Bot, PLAYSTYLES } from '../src/sim/bot';
import { ERAS } from '../src/content/eras';
import { fmt, fmtTime } from '../src/core/format';
import { PRODUCERS } from '../src/content/producers';

const hours = Number(process.argv[2] ?? 8);
const checkpoints = [60, 300, 900, 1800, 3600, 7200, 14400, 28800].filter((c) => c <= hours * 3600);

const lines: string[] = [];
const out = (l = ''): void => {
  lines.push(l);
  console.log(l);
};

out(`# Balance report`);
out();
out(`Generated by \`pnpm balance ${hours}\`: ${hours}h of simulated play per style, using the real game simulation.`);
out();
out('## Pacing targets');
out();
out('| Milestone | Intensive (8 pokes/s) | Casual (4 pokes/s, half the time) | Mostly idle |');
out('|---|---|---|---|');
out('| First boss (Era II) | ~1 min | ~3–4 min | ~20 min |');
out('| Era IV (prestige unlocks) | ~10 min | ~20 min | ~1.5 h |');
out('| Era V | ~30 min | ~1–1.5 h | ~3.5 h |');
out('| Era VII | ~2 h | ~5–7 h (faster with prestige) | — |');
out();
out('Design notes: clicking dominates the first minutes; from Era III on, minions and "% of production" pokes carry the');
out('economy so idle play stays viable (roughly 3× slower than casual). Bosses are real gates: they need ~15–25% of the era');
out('threshold in gasps within 30 s, so players occasionally have to build up and retry. Paranoia (prestige) is cube-root of');
out('lifetime gasps, and the unspent bonus is softcapped past 250 points so late timelines plateau instead of exploding.');
out();

const rows: string[][] = [];
for (const [key, style] of Object.entries(PLAYSTYLES)) {
  const t0 = performance.now();
  const bot = new Bot(style);
  const snaps: string[] = [];
  let elapsed = 0;
  for (const c of checkpoints) {
    bot.run(c - elapsed);
    elapsed = c;
    const s = bot.game.state;
    const minions = PRODUCERS.reduce((a, p) => a + (s.producers[p.id] ?? 0), 0);
    snaps.push(`| ${fmtTime(c)} | ${ERAS[s.era].numeral} | ${fmt(s.runGasps)} | ${fmt(bot.game.gpsBase)}/s | ${fmt(bot.game.pokeValue)} | ${s.weapon + 1} | ${minions} | ${Object.keys(s.upgrades).length} | ${s.paranoiaEarned} |`);
  }
  out(`## ${style.name} (\`${key}\`)`);
  out();
  out(`| Time | Era | Run gasps | Production | Poke | Weapons | Minions | Upgrades | Paranoia |`);
  out(`|---|---|---|---|---|---|---|---|---|`);
  for (const l of snaps) out(l);
  out();
  const eras = ERAS.map((e, i) => (bot.eraTimes[i] !== undefined ? `${e.numeral} ${fmtTime(bot.eraTimes[i])}` : `${e.numeral} —`)).join(' · ');
  out(`Era reached (first timeline): ${eras}`);
  out(`Boss failures: ${bot.bossFails} · Collapses: ${bot.collapses} · Victory: ${bot.victoryAt >= 0 ? fmtTime(bot.victoryAt) : 'no'}`);
  if (bot.log.length) out(`Prestige log: ${bot.log.join('; ')}`);
  out(`(simulated in ${((performance.now() - t0) / 1000).toFixed(1)}s)`);
  out();
  rows.push([style.name, ...ERAS.map((_, i) => (bot.eraTimes[i] !== undefined ? fmtTime(bot.eraTimes[i]) : '—'))]);
}

out(`## Era arrival summary (first timeline)`);
out();
out(`| Style | ${ERAS.map((e) => e.numeral).join(' | ')} |`);
out(`|---|${ERAS.map(() => '---').join('|')}|`);
for (const r of rows) out(`| ${r.join(' | ')} |`);

mkdirSync('docs', { recursive: true });
writeFileSync('docs/balance.md', lines.join('\n') + '\n');
